#!/usr/bin/env node
// Builds albera-setup.exe (docs/architecture/control-plane-service.md section 8, PR6) as a NativeAOT program. It only builds: nothing here installs, registers, elevates or starts it.
// Output is git-ignored. dotnet runs through scripts/dotnet-build-env.mjs (trusted dotnet.exe, sanitised environment, locked restore with the repo NuGet config).
//
//   node scripts/publish-windows-setup.mjs --gh <gh.exe> --trusted-root <trusted_root.jsonl>
//       The release build. NativeAOT needs the MSVC linker, which the development PC does not have, so this runs in CI (windows-latest) only; the workflow attests the result.
//       The SHA-256 of the two files is compiled into setup (a generated PinnedTools.g.cs in a temp folder, passed as AlberaPinnedToolsSource): setup then refuses a gh.exe or a trusted root
//       that is not exactly these bytes. The same file carries the run id of this build (GITHUB_RUN_ID, set by GitHub Actions): setup never installs an update attested from an OLDER run (anti-rollback floor).
//       A release build without a valid GITHUB_RUN_ID is refused.
//   node scripts/publish-windows-setup.mjs --compile-check
//       Compiles the same sources as ordinary .NET (PublishAot=false, no linker, nothing downloaded beyond what every other build here restores) into a temp folder that is thrown away,
//       with all-zero pins and run id 0. It proves the project builds under the hardened environment and the AOT analyzers; the output is NOT a release artifact and refuses to install.
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { createBuildContextOrExit, printBuildIdentity, requireHostBuildSdk, restoreAndBuild } from './dotnet-build-env.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SETUP_DIRECTORY = 'windows-setup';
export const SETUP_EXECUTABLE = 'albera-setup.exe';
const ZERO_HASH = '0'.repeat(64);

/** @returns {{ compileCheck: boolean, gh?: string, trustedRoot?: string }} or throws `usage: ...` */
export function parseArguments(argv) {
  const usage = 'usage: publish-windows-setup.mjs --gh <gh.exe> --trusted-root <trusted_root.jsonl> | --compile-check';
  const values = new Map();
  let compileCheck = false;
  for (let i = 0; i < argv.length; i += 1) {
    const name = argv[i];
    if (name === '--compile-check') { compileCheck = true; continue; }
    if ((name === '--gh' || name === '--trusted-root') && i + 1 < argv.length && !values.has(name)) { values.set(name, argv[i += 1]); continue; }
    throw new Error(usage);
  }
  if (compileCheck) {
    if (values.size > 0) throw new Error(usage);
    return { compileCheck };
  }
  if (!values.has('--gh') || !values.has('--trusted-root')) throw new Error(usage);
  return { compileCheck, gh: values.get('--gh'), trustedRoot: values.get('--trusted-root') };
}

const sha256OfFile = (file) => createHash('sha256').update(fs.readFileSync(file)).digest('hex');

const MAX_UINT64 = (1n << 64n) - 1n;

/** The run id of the CI run that builds setup, from GITHUB_RUN_ID: a decimal number that fits an unsigned 64-bit integer, no sign, no leading zero. */
export function parseBuildRunId(text) {
  if (typeof text !== 'string' || !/^(0|[1-9][0-9]{0,19})$/u.test(text) || BigInt(text) > MAX_UINT64) throw new Error(`not a run id: ${text}`);
  return text;
}

/** The source file that gives setup its two pins and the run id of its own build (C# constants). The run id is a floor: 0 (a compile check) bounds nothing. */
export function pinnedToolsSource(ghSha256, trustedRootSha256, buildRunId = '0') {
  for (const hash of [ghSha256, trustedRootSha256]) if (!/^[0-9a-f]{64}$/u.test(hash)) throw new Error(`not a SHA-256: ${hash}`);
  parseBuildRunId(buildRunId);
  return [
    '// Generated by scripts/publish-windows-setup.mjs. Do not edit; it is not in the repository.',
    'namespace Albera.Setup;',
    '',
    'internal static class PinnedTools',
    '{',
    `    public const string GhSha256 = "${ghSha256}";`,
    `    public const string TrustedRootSha256 = "${trustedRootSha256}";`,
    `    public const ulong BuildRunId = ${buildRunId}UL;`,
    '}',
    '',
  ].join('\n');
}

function requireRegularFile(file, label) {
  const stat = fs.lstatSync(file, { throwIfNoEntry: false });
  if (!stat || !stat.isFile() || stat.isSymbolicLink()) { process.stderr.write(`${label}: ${file} is not a regular file\n`); process.exit(1); }
  if (stat.size === 0) { process.stderr.write(`${label}: ${file} is empty\n`); process.exit(1); }
}

function main() {
  if (process.platform !== 'win32') {
    console.log('Windows setup build skipped on non-Windows host');
    return;
  }
  if (process.arch !== 'x64') throw new Error('windows_setup_requires_x64');
  let parsed;
  try { parsed = parseArguments(process.argv.slice(2)); } catch (error) { process.stderr.write(`${error.message}\n`); process.exit(2); }

  let ghSha256 = ZERO_HASH;
  let trustedRootSha256 = ZERO_HASH;
  if (!parsed.compileCheck) {
    requireRegularFile(parsed.gh, 'gh.exe');
    requireRegularFile(parsed.trustedRoot, 'trusted root');
    if (!fs.readFileSync(parsed.trustedRoot).subarray(-1).equals(Buffer.from('\n'))) { process.stderr.write('trusted root must end with a line feed (gh skips an unterminated last line)\n'); process.exit(1); }
    ghSha256 = sha256OfFile(parsed.gh);
    trustedRootSha256 = sha256OfFile(parsed.trustedRoot);
  }

  let buildRunId = '0';
  if (!parsed.compileCheck) {
    try { buildRunId = parseBuildRunId(process.env.GITHUB_RUN_ID); } catch { process.stderr.write('GITHUB_RUN_ID is not set to a run id: a release setup is built by a workflow run (its id is the anti-rollback floor compiled into setup)\n'); process.exit(1); }
  }

  const generated = fs.mkdtempSync(path.join(os.tmpdir(), 'albera-setup-pins-'));
  process.once('exit', () => { try { fs.rmSync(generated, { recursive: true, force: true }); } catch { /* a leftover temp folder is harmless */ } });
  const pinnedSource = path.join(generated, 'PinnedTools.g.cs');
  fs.writeFileSync(pinnedSource, pinnedToolsSource(ghSha256, trustedRootSha256, buildRunId), 'utf8');

  const project = path.join(root, 'src', 'runtime', SETUP_DIRECTORY, 'Albera.Setup.csproj');
  const context = createBuildContextOrExit(root);
  const sdk = requireHostBuildSdk(context);
  const properties = ['-p:EnableWindowsTargeting=true', '-p:RestorePackagesWithLockFile=true', '-p:RestoreLockedMode=true', `-p:AlberaPinnedToolsSource=${pinnedSource}`, `-p:PublishAot=${parsed.compileCheck ? 'false' : 'true'}`];

  if (parsed.compileCheck) {
    const output = fs.mkdtempSync(path.join(os.tmpdir(), 'albera-setup-compile-check-'));
    process.once('exit', () => { try { fs.rmSync(output, { recursive: true, force: true }); } catch { /* a leftover temp folder is harmless */ } });
    // The lock file is written for the NativeAOT build (it pins Microsoft.DotNet.ILCompiler and ILLink.Tasks), so the restore uses PublishAot=true even here; only the build compiles without AOT.
    restoreAndBuild(context, { label: 'Windows setup (compile check)', verb: 'build', project, runtime: 'win-x64', args: ['--configuration', 'Release', '--runtime', 'win-x64', '--output', output], properties, restoreProperties: properties.map((p) => (p === '-p:PublishAot=false' ? '-p:PublishAot=true' : p)) });
    console.log(`dotnet sdk ${sdk}`);
    console.log('Windows setup compiles (compile check only: ordinary .NET, zero pins, thrown away; the NativeAOT bytes are made in CI)');
    return;
  }

  const output = path.join(root, 'src', 'runtime', SETUP_DIRECTORY, 'bin', 'Release', 'net10.0-windows', 'win-x64', 'publish');
  restoreAndBuild(context, { label: 'Windows setup', project, runtime: 'win-x64', args: ['--configuration', 'Release', '--runtime', 'win-x64', '--output', output], properties });
  const executable = path.join(output, SETUP_EXECUTABLE);
  requireRegularFile(executable, 'albera-setup.exe');
  printBuildIdentity({ sdk, root, file: executable, sha256: sha256OfFile(executable) });
  console.log(`pinned gh.exe sha256 ${ghSha256}`);
  console.log(`pinned trusted root sha256 ${trustedRootSha256}`);
  console.log('Windows setup published for win-x64 as NativeAOT (build output is ignored by Git; not installed, not started)');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
